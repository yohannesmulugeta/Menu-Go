create or replace function public.is_restaurant_member(target_restaurant uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.restaurant_members rm
    where rm.restaurant_id = target_restaurant
      and rm.user_id = auth.uid()
  );
$$;

create policy "public read active restaurants"
on public.restaurants for select
using (status = 'active' or public.is_restaurant_member(id));

create policy "members update restaurant"
on public.restaurants for update
using (public.is_restaurant_member(id))
with check (public.is_restaurant_member(id));

create policy "members read memberships"
on public.restaurant_members for select
using (user_id = auth.uid() or public.is_restaurant_member(restaurant_id));

create policy "public read active categories"
on public.categories for select
using (
  exists (
    select 1 from public.restaurants r
    where r.id = restaurant_id and r.status = 'active'
  )
  or public.is_restaurant_member(restaurant_id)
);

create policy "members manage categories"
on public.categories for all
using (public.is_restaurant_member(restaurant_id))
with check (public.is_restaurant_member(restaurant_id));

